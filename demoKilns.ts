function generateAdditionalDistrictKilns(): Kiln[] {
  const result: Kiln[] = [];
  // Defined seed sites in sub-zones
  const subZones = [
    { baseLat: 26.9200, baseLon: 80.8100, tile: 'tile_042' },
    { baseLat: 26.8800, baseLon: 80.9900, tile: 'tile_088' },
    { baseLat: 26.8100, baseLon: 81.0800, tile: 'tile_104' },
    { baseLat: 26.7600, baseLon: 80.9200, tile: 'tile_119' },
    { baseLat: 26.7000, baseLon: 81.1400, tile: 'tile_205' },
    { baseLat: 27.0300, baseLon: 80.8700, tile: 'tile_312' },
  ];

  let idCounter = 60;

  subZones.forEach((zone, zIdx) => {
    // Generate pairs for 2023-24 and 2025-26
    for (let i = 0; i < 6; i++) {
      const latOffset = (Math.sin(zIdx * 3 + i * 2) * 0.018);
      const lonOffset = (Math.cos(zIdx * 2 + i * 3) * 0.022);
      const kLat = zone.baseLat + latOffset;
      const kLon = zone.baseLon + lonOffset;

      const id23 = `KLN-2023-${String(idCounter).padStart(3, '0')}`;
      const id25 = `KLN-2025-${String(idCounter).padStart(3, '0')}`;
      idCounter++;

      const isRegistered = i !== 3; // some unregistered
      const claimedConv = i % 2 === 0;

      // 2023 baseline
      result.push({
        id: id23,
        lat: Number(kLat.toFixed(4)),
        lon: Number(kLon.toFixed(4)),
        class: 'FCBK',
        confidence: Number((0.78 + (i % 4) * 0.05).toFixed(2)),
        angle_deg: (i * 28 + zIdx * 15) % 180,
        width_m: 24 + (i % 4),
        height_m: 65 + (i % 5) * 2,
        period: '2023-24',
        tile_id: zone.tile,
        in_register: isRegistered,
        claimed_conversion: claimedConv,
        coordinate_precision: '±10m (Sentinel-2 10m GSD)',
        source: 'SentinelKilnDB / S2-L2A baseline',
      });

      // Outcome in 2025
      if (i === 0 || i === 4) {
        // Converted to Zigzag
        result.push({
          id: id25,
          lat: Number((kLat + 0.0002).toFixed(4)),
          lon: Number((kLon + 0.0002).toFixed(4)),
          class: 'Zigzag',
          confidence: Number((0.82 + (i % 3) * 0.06).toFixed(2)),
          angle_deg: (i * 28 + zIdx * 15) % 180,
          width_m: 23,
          height_m: 62,
          period: '2025-26',
          tile_id: zone.tile,
          in_register: isRegistered,
          coordinate_precision: '±10m (Sentinel-2 10m GSD)',
          source: 'SentinelKilnDB / S2-L2A 2025-26',
        });
      } else if (i === 1) {
        // Still FCBK!
        result.push({
          id: id25,
          lat: Number((kLat + 0.0001).toFixed(4)),
          lon: Number((kLon + 0.0003).toFixed(4)),
          class: 'FCBK',
          confidence: Number((0.74 + (i % 3) * 0.07).toFixed(2)),
          angle_deg: (i * 28 + zIdx * 15) % 180,
          width_m: 25,
          height_m: 68,
          period: '2025-26',
          tile_id: zone.tile,
          in_register: isRegistered,
          claimed_conversion: claimedConv,
          coordinate_precision: '±10m (Sentinel-2 10m GSD)',
          source: 'SentinelKilnDB / S2-L2A 2025-26',
        });
      } else if (i === 2) {
        // Unclear (low confidence 0.45 or 0.48)
        result.push({
          id: id25,
          lat: Number((kLat + 0.0002).toFixed(4)),
          lon: Number((kLon - 0.0002).toFixed(4)),
          class: i % 2 === 0 ? 'FCBK' : 'Zigzag',
          confidence: 0.47,
          angle_deg: (i * 28 + zIdx * 15) % 180,
          width_m: 24,
          height_m: 64,
          period: '2025-26',
          tile_id: zone.tile,
          in_register: isRegistered,
          coordinate_precision: '±10m (Sentinel-2 10m GSD)',
          source: 'SentinelKilnDB / S2-L2A 2025-26',
        });
      } else if (i === 3) {
        // Demolished (no 2025 detection generated for this 2023 site)
      } else {
        // Converted to rare CFCBK
        result.push({
          id: id25,
          lat: Number((kLat + 0.0001).toFixed(4)),
          lon: Number((kLon + 0.0001).toFixed(4)),
          class: 'CFCBK',
          confidence: 0.72,
          angle_deg: 0,
          width_m: 33,
          height_m: 33,
          period: '2025-26',
          tile_id: zone.tile,
          in_register: isRegistered,
          coordinate_precision: '±10m (Sentinel-2 10m GSD)',
          source: 'SentinelKilnDB / S2-L2A 2025-26',
        });
      }
    }

    // Add 2 brand new 2025 detections in this zone (not existing in 2023)
    for (let j = 0; j < 2; j++) {
      const newLat = zone.baseLat + 0.015 * (j === 0 ? 1 : -1) + 0.004;
      const newLon = zone.baseLon + 0.014 * (j === 0 ? -1 : 1) + 0.005;
      const newId = `KLN-2025-NEW-${String(idCounter).padStart(3, '0')}`;
      idCounter++;

      const isFCBK = j === 0;
      const conf = j === 0 ? 0.62 : 0.88; // one uncertain, one high
      result.push({
        id: newId,
        lat: Number(newLat.toFixed(4)),
        lon: Number(newLon.toFixed(4)),
        class: isFCBK ? 'FCBK' : 'Zigzag',
        confidence: conf,
        angle_deg: (j * 45 + zIdx * 20) % 180,
        width_m: 25,
        height_m: 68,
        period: '2025-26',
        tile_id: zone.tile,
        in_register: j === 1, // unregistered if j === 0
        coordinate_precision: '±10m (Sentinel-2 10m GSD)',
        source: 'SentinelKilnDB / S2-L2A 2025-26',
      });
    }
  });

  return result;
}

